export type AbordagemId = "cuidadoso" | "esperto" | "estiloso" | "poderoso" | "agil" | "sorrateiro";

export type Arquetipo = ClasseDef & {
  /** abordagens da maior para a menor: recebem +3, +2, +2, +1, +1, +0 */
  ordem: [AbordagemId, AbordagemId, AbordagemId, AbordagemId, AbordagemId, AbordagemId];
  /** abordagem preferida para atacar, defender e (quando faz sentido) usar poderes */
  ataque: AbordagemId;
  defesa: AbordagemId;
  magia?: AbordagemId;
  /** façanhas de exemplo no formato do FAE */
  facanhas: string[];
};

const FONTE = "Fate Acelerado (adaptação da taverna)";

// atalho para não repetir campos fixos em 36 entradas
function a(
  id: string,
  nome: string,
  descricao: string,
  papel: string,
  ordem: Arquetipo["ordem"],
  combate: { ataque: AbordagemId; defesa: AbordagemId; magia?: AbordagemId },
  equipamento: string[],
  facanhas: string[],
): Arquetipo {
  return { id, nome, descricao, papel, ordem, atributoChave: ordem[0], pvBase: 3, pericias: [], equipamento, fonte: FONTE, facanhas, ...combate };
}

